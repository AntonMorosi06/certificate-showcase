const categories = ["Tutti","AI & Data","Software & UX","Cybersecurity","Apple Teacher","Lingue","Scuola & Workshop"];
let activeCategory = "Tutti";
let query = "";

const grid = document.querySelector("[data-grid]");
const filters = document.querySelector("[data-filters]");
const search = document.querySelector("[data-search]");
const domainGrid = document.querySelector("[data-domain-grid]");
const timeline = document.querySelector("[data-timeline]");
const dialog = document.querySelector("[data-dialog]");
const detail = document.querySelector("[data-detail]");
const closeButton = document.querySelector("[data-close]");

function byCategory() {
  return certificates.reduce((acc, item) => {
    acc[item.category] = acc[item.category] || [];
    acc[item.category].push(item);
    return acc;
  }, {});
}

function textMatch(item) {
  const haystack = [item.title, item.issuer, item.platform, item.category, item.summary, ...item.skills].join(" ").toLowerCase();
  return haystack.includes(query.toLowerCase());
}

function filtered() {
  return certificates.filter((item) => (activeCategory === "Tutti" || item.category === activeCategory) && textMatch(item));
}

function renderFilters() {
  filters.innerHTML = categories.map((category) => {
    const pressed = category === activeCategory ? "true" : "false";
    return `<button type="button" aria-pressed="${pressed}" data-category="${category}">${category}</button>`;
  }).join("");
}

function renderDomains() {
  const grouped = byCategory();
  const descriptions = {
    "AI & Data": "AI generativa, machine learning, prompt engineering, deep research e agenti.",
    "Cybersecurity": "Fondamenti, rischio, reti, networking sicuro ed ethical hacking introduttivo.",
    "Software & UX": "Programmazione, UI/UX, portfolio, basi computer e logica di interfaccia.",
    "Apple Teacher": "Riconoscimenti Apple Education e Swift Playgrounds.",
    "Lingue": "Cambridge, ILS, EFSET e certificazioni internazionali con focus inglese.",
    "Scuola & Workshop": "Workshop, proprietà intellettuale e scambio internazionale."
  };

  domainGrid.innerHTML = Object.entries(grouped).map(([category, items]) => `
    <article class="domain-card reveal" style="border-top: 5px solid ${items[0].accent}">
      <strong>${items.length}</strong>
      <h3>${category}</h3>
      <p>${descriptions[category]}</p>
    </article>
  `).join("");
}

function renderGrid() {
  const data = filtered();
  grid.innerHTML = data.map((item) => `
    <article class="card reveal" style="--accent:${item.accent}">
      <div class="card-media"><img src="${item.thumb}" alt="${item.title}"></div>
      <div class="card-body">
        <div class="meta"><span>${item.category}</span><span>${item.date}</span></div>
        <h3>${item.title}</h3>
        <p>${item.summary}</p>
        <div class="skills">${item.skills.map((skill) => `<span>${skill}</span>`).join("")}</div>
        <button type="button" data-open="${item.id}">Dettagli</button>
      </div>
    </article>
  `).join("");
  observeReveals();
}

function renderTimeline() {
  const grouped = certificates.reduce((acc, item) => {
    acc[item.year] = acc[item.year] || [];
    acc[item.year].push(item);
    return acc;
  }, {});
  timeline.innerHTML = Object.entries(grouped)
    .sort((a, b) => Number(b[0]) - Number(a[0]))
    .map(([year, items]) => `
      <div class="year-row">
        <div class="year">${year}</div>
        <div class="year-items">
          ${items.map((item) => `
            <article class="timeline-item reveal" style="--accent:${item.accent}">
              <h3>${item.title}</h3>
              <p>${item.issuer} · ${item.date}</p>
            </article>
          `).join("")}
        </div>
      </div>
    `).join("");
}

function openDetail(id) {
  const item = certificates.find((entry) => entry.id === id);
  if (!item) return;
  detail.innerHTML = `
    <div class="detail-image"><img src="${item.image}" alt="${item.title}"></div>
    <div class="detail-copy">
      <div class="meta"><span>${item.category}</span><span>${item.date}</span></div>
      <h2>${item.title}</h2>
      <p><strong>${item.issuer}</strong> · ${item.platform}</p>
      ${item.publicNote ? `<p>${item.publicNote}</p>` : ""}
      ${item.details.map((paragraph) => `<p>${paragraph}</p>`).join("")}
      <div class="skills">${item.skills.map((skill) => `<span>${skill}</span>`).join("")}</div>
      ${item.verify ? `<a class="verify" href="${item.verify}" target="_blank" rel="noreferrer">Verifica certificato</a>` : ""}
    </div>
  `;
  dialog.showModal();
}

function observeReveals() {
  const nodes = document.querySelectorAll(".reveal:not(.is-visible)");
  if (!("IntersectionObserver" in window)) {
    nodes.forEach((node) => node.classList.add("is-visible"));
    return;
  }
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: .12 });
  nodes.forEach((node) => observer.observe(node));
}

filters.addEventListener("click", (event) => {
  const button = event.target.closest("[data-category]");
  if (!button) return;
  activeCategory = button.dataset.category;
  renderFilters();
  renderGrid();
});

search.addEventListener("input", (event) => {
  query = event.target.value.trim();
  renderGrid();
});

grid.addEventListener("click", (event) => {
  const button = event.target.closest("[data-open]");
  if (button) openDetail(button.dataset.open);
});

closeButton.addEventListener("click", () => dialog.close());
dialog.addEventListener("click", (event) => {
  if (event.target === dialog) dialog.close();
});

renderFilters();
renderDomains();
renderTimeline();
renderGrid();
observeReveals();
